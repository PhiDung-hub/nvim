local function blend(fg, amount)
  local function ch(hex, i) return tonumber(hex:sub(i, i + 1), 16) end
  local out = "#"
  for i = 2, 6, 2 do
    out = out .. string.format("%02x", math.floor(ch(fg, i) * amount + ch(t.ground, i) * (1 - amount) + 0.5))
  end
  return out
end

